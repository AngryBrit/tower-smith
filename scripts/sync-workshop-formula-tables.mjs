/**
 * Regenerates src/data/workshopFormulaTables.ts from tables/workshop/formulas/ JSON.
 *
 * Run: node scripts/sync-workshop-formula-tables.mjs
 */

import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')
const formulasBase = path.join(root, 'tables/workshop/formulas')
const outFile = path.join(root, 'src/data/workshopFormulaTables.ts')

function collectFormulaFiles() {
  const files = []
  function walk(dir, relPrefix = '') {
    for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
      const rel = relPrefix ? `${relPrefix}/${ent.name}` : ent.name
      const abs = path.join(dir, ent.name)
      if (ent.isDirectory()) walk(abs, rel)
      else if (ent.name.endsWith('.json')) {
        const doc = JSON.parse(fs.readFileSync(abs, 'utf8'))
        files.push({
          rel: rel.replace(/\\/g, '/'),
          workshopKey: doc.workshopKey,
          category: doc.category ?? 'utility',
        })
      }
    }
  }
  if (fs.existsSync(formulasBase)) walk(formulasBase)
  return files.sort((a, b) => a.workshopKey.localeCompare(b.workshopKey))
}

const files = collectFormulaFiles()

const imports = files
  .map(
    (f, i) =>
      `import formula${i} from '../../tables/workshop/formulas/${f.rel}' with { type: 'json' }`,
  )
  .join('\n')

const entries = files
  .map((f, i) => `  '${f.workshopKey}': formula${i} as WorkshopFormulaSpec,`)
  .join('\n')

const utilityCount = files.filter((f) => f.category === 'utility').length
const attackCount = files.filter((f) => f.category === 'attack').length
const defenseCount = files.filter((f) => f.category === 'defense').length

const body = `/**
 * Authoritative workshop display-card formula specs from \`tables/workshop/formulas/\`.
 * Generated by scripts/sync-workshop-formula-tables.mjs — do not hand-edit.
 */

import type { WorkshopFormulaSpec } from './workshopFormulaTypes'
${imports}

export const WORKSHOP_FORMULA_COUNT = ${files.length}
export const WORKSHOP_UTILITY_FORMULA_COUNT = ${utilityCount}
export const WORKSHOP_ATTACK_FORMULA_COUNT = ${attackCount}
export const WORKSHOP_DEFENSE_FORMULA_COUNT = ${defenseCount}

const workshopFormulaByKey: Record<string, WorkshopFormulaSpec> = {
${entries}
}

export function getWorkshopFormulaSpec(workshopKey: string): WorkshopFormulaSpec | undefined {
  return workshopFormulaByKey[workshopKey]
}

export function getWorkshopAttackFormulaSpec(workshopKey: string): WorkshopFormulaSpec | undefined {
  const spec = workshopFormulaByKey[workshopKey]
  return spec?.category === 'attack' ? spec : undefined
}

export function getWorkshopDefenseFormulaSpec(workshopKey: string): WorkshopFormulaSpec | undefined {
  const spec = workshopFormulaByKey[workshopKey]
  return spec?.category === 'defense' ? spec : undefined
}

export function getWorkshopFormulaSpecs(): Readonly<Record<string, WorkshopFormulaSpec>> {
  return workshopFormulaByKey
}

export function getWorkshopAttackFormulaSpecs(): Readonly<Record<string, WorkshopFormulaSpec>> {
  const out: Record<string, WorkshopFormulaSpec> = {}
  for (const [key, spec] of Object.entries(workshopFormulaByKey)) {
    if (spec.category === 'attack') out[key] = spec
  }
  return out
}

export function getWorkshopDefenseFormulaSpecs(): Readonly<Record<string, WorkshopFormulaSpec>> {
  const out: Record<string, WorkshopFormulaSpec> = {}
  for (const [key, spec] of Object.entries(workshopFormulaByKey)) {
    if (spec.category === 'defense') out[key] = spec
  }
  return out
}
`

fs.writeFileSync(outFile, body)
console.log(
  `Wrote ${outFile} (${files.length} formulas: ${utilityCount} utility, ${attackCount} attack, ${defenseCount} defense)`,
)
