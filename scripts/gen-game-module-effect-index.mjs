/**
 * Generate game ModuleManager.effects index → workshop sub-module pick mapping.
 *
 * Game `ModuleItem.effects[]` stores indices into `ModuleManager.effects` (0 = empty slot).
 * Table order: cannon → armor → generator → core (wiki catalog order except core — game
 * SubstatsCluster row order); within each row, common … ancestral, skip null wiki cells.
 *
 * On cannon/armor/generator rows with a Common wiki column, in-game sparse offset N uses the
 * wiki tier at max(0, N − 1) (e.g. crit index 7 → Common +2%, not Rare +3%).
 *
 * Generator rows that start at Epic (no Common/Rare) map sparse offset → wiki tier in order
 * (Package Chance, Enemy Level Skip, etc.). Ancestral merge modules may store the row base
 * index; import bumps +3 when decode is Epic on an Ancestral-tier chassis (see import helper).
 *
 * Run: npx tsx scripts/gen-game-module-effect-index.mjs
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { submoduleEffectId } from '../src/data/workshopSubmoduleCatalog.ts'
import { gameEffectRowsForSlot } from './lib/game-module-effect-rows.mjs'
import { touchWikiDataStamp } from './lib/wiki-data-stamp.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outPath = join(root, 'src/playerSave/gameModuleEffectIndex.ts')

const SLOT_ORDER = ['cannon', 'armor', 'generator', 'core']
const RARITIES = ['common', 'rare', 'epic', 'legendary', 'mythic', 'ancestral']

function wikiTiersForRow(row) {
  return RARITIES.filter((r) => row.cells[r] != null)
}

/**
 * Map sparse row offset → workshop rarity (wiki column key for substat value).
 */
const GENERATOR_WIKI_TIER_ROW_LABELS = new Set([
  'Package Chance [%]',
  'Enemy Attack Level Skip [%]',
  'Enemy Health Level Skip [%]',
])

function gameValueRarityForSparseRowEntry(row, offsetInRow, slot) {
  const firstNonNull = RARITIES.findIndex((r) => row.cells[r] != null)
  if (
    slot === 'generator' &&
    firstNonNull >= 2 &&
    GENERATOR_WIKI_TIER_ROW_LABELS.has(row.label)
  ) {
    return wikiTiersForRow(row)[offsetInRow]
  }
  if (firstNonNull === 0 && slot !== 'core') {
    const tiers = wikiTiersForRow(row)
    const wikiOffset = Math.max(0, offsetInRow - 1)
    const rarity = tiers[wikiOffset]
    if (rarity == null || row.cells[rarity] == null) {
      throw new Error(`No wiki cell for ${row.label} at offset ${wikiOffset}`)
    }
    return rarity
  }
  let fixedSlot
  if (firstNonNull === 0) {
    fixedSlot = offsetInRow >= 3 ? offsetInRow - 1 : offsetInRow + 3
  } else {
    fixedSlot = offsetInRow + firstNonNull
    if (firstNonNull >= 1 && firstNonNull <= 3 && fixedSlot >= 4) fixedSlot -= 1
  }
  const rarity = RARITIES[fixedSlot]
  if (rarity == null || row.cells[rarity] == null) {
    throw new Error(`No wiki cell for ${row.label} at game tier ${String(rarity)}`)
  }
  return rarity
}

/** @type {{ slot: string; effectId: string; rarity: string }[]} */
const ENTRIES = []
for (const slot of SLOT_ORDER) {
  for (const row of gameEffectRowsForSlot(slot)) {
    const effectId = submoduleEffectId(row.label)
    let offsetInRow = 0
    for (const wikiRarity of RARITIES) {
      if (row.cells[wikiRarity] == null) continue
      ENTRIES.push({
        slot,
        effectId,
        rarity: gameValueRarityForSparseRowEntry(row, offsetInRow, slot),
      })
      offsetInRow++
    }
  }
}

const lines = ENTRIES.map((entry, index) => {
  return `  { slot: ${JSON.stringify(entry.slot)}, effectId: ${JSON.stringify(entry.effectId)}, rarity: ${JSON.stringify(entry.rarity)} }, // ${index}`
})

const ts = `/**
 * Game \`ModuleManager.effects\` index → workshop sub-module effect pick.
 * Generated by \`scripts/gen-game-module-effect-index.mjs\` from wiki submodule tables.
 */

import type { WorkshopChassisModuleMergeTier } from '../data/workshopChassisModuleShared'
import { workshopChassisModuleEffectTier } from '../data/workshopChassisModuleShared'
import type { WorkshopAssistModuleSlot } from '../data/workshopSimModules'
import type { WorkshopSubmoduleRarity } from '../data/workshopSubmoduleEffects'
import { WORKSHOP_SUBMODULE_SLOT_COUNT } from '../data/workshopSubmoduleCatalog'
import type {
  WorkshopSubmoduleOrderedSlots,
  WorkshopSubmoduleSelectionMap,
} from '../data/workshopSubmoduleSelection'

export type GameModuleEffectDecode = {
  slot: WorkshopAssistModuleSlot
  effectId: string
  rarity: WorkshopSubmoduleRarity
}

export const GAME_MODULE_EFFECT_COUNT = ${ENTRIES.length} as const

/** Save effect index → decoded pick (\`null\` if out of range). Index 0 is Attack Speed common. */
export const GAME_MODULE_EFFECT_BY_INDEX: readonly GameModuleEffectDecode[] = [
${lines.join('\n')}
] as const

export function gameModuleEffectByIndex(
  index: number,
  moduleLevel = 0,
): GameModuleEffectDecode | null {
  if (!Number.isFinite(index) || index < 0) return null
  let i = Math.trunc(index)
  const level = Number.isFinite(moduleLevel) ? Math.max(0, Math.trunc(moduleLevel)) : 0
  // High-level modules store sparseIndex + level when that sum reaches the table size (330).
  if (i >= GAME_MODULE_EFFECT_COUNT && level > 0) {
    i -= level
  }
  if (i < 0 || i >= GAME_MODULE_EFFECT_COUNT) return null
  return GAME_MODULE_EFFECT_BY_INDEX[i] ?? null
}

/** Decode save effect index for a chassis slot (assist may use primary module level offset). */
export function gameModuleEffectByIndexForSlot(
  index: number,
  slot: WorkshopAssistModuleSlot,
  moduleLevel = 0,
  primaryModuleLevel = 0,
): GameModuleEffectDecode | null {
  const matchSlot = (decoded: GameModuleEffectDecode | null): GameModuleEffectDecode | null =>
    decoded != null && decoded.slot === slot ? decoded : null

  const direct = matchSlot(gameModuleEffectByIndex(index, moduleLevel))
  if (direct != null) return direct

  const primaryLevel = Number.isFinite(primaryModuleLevel)
    ? Math.max(0, Math.trunc(primaryModuleLevel))
    : 0
  if (primaryLevel > 0) {
    return matchSlot(gameModuleEffectByIndex(index - primaryLevel, 0))
  }
  return null
}

function decodeGeneratorEffectAtIndex(
  index: number,
  moduleLevel: number,
): GameModuleEffectDecode | null {
  const decoded = gameModuleEffectByIndex(index, moduleLevel)
  return decoded != null && decoded.slot === 'generator' ? decoded : null
}

/**
 * Decode save effect index for submodule import.
 * Main ancestral-tier generator modules store the Epic row base index for Epic-only substat rows;
 * bump +3 when that decodes as Epic but Ancestral exists in the same row.
 * Generator assist encodes vs primary chassis level: sparse+primary≥330 → stored as sparse+primary−10;
 * ancestral-family assist may store mythic/ancestral picks as raw−3.
 */
function gameModuleEffectForSubmoduleImport(
  raw: number,
  slot: WorkshopAssistModuleSlot,
  moduleLevel: number,
  primaryModuleLevel: number,
  chassisMerge?: WorkshopChassisModuleMergeTier | null,
): GameModuleEffectDecode | null {
  const primaryLevel = Number.isFinite(primaryModuleLevel)
    ? Math.max(0, Math.trunc(primaryModuleLevel))
    : 0
  const rawIndex = Math.trunc(raw)

  if (slot === 'generator' && primaryLevel > 0) {
    const candidates: number[] = []
    const levelEncoded = rawIndex + 10 - primaryLevel
    if (levelEncoded >= 0) candidates.push(levelEncoded)
    if (
      chassisMerge != null &&
      workshopChassisModuleEffectTier(chassisMerge) === 'ancestral' &&
      rawIndex + 3 < GAME_MODULE_EFFECT_COUNT
    ) {
      candidates.push(rawIndex + 3)
    }
    for (const cand of candidates) {
      const hit =
        decodeGeneratorEffectAtIndex(cand, moduleLevel) ??
        decodeGeneratorEffectAtIndex(cand, 0)
      if (hit != null) return hit
    }
  }

  const decoded = gameModuleEffectByIndexForSlot(
    raw,
    slot,
    moduleLevel,
    primaryModuleLevel,
  )
  if (decoded == null) return null
  if (
    slot === 'generator' &&
    chassisMerge != null &&
    workshopChassisModuleEffectTier(chassisMerge) === 'ancestral' &&
    rawIndex < GAME_MODULE_EFFECT_COUNT &&
    decoded.rarity === 'epic'
  ) {
    const ancestral =
      decodeGeneratorEffectAtIndex(rawIndex + 3, moduleLevel) ??
      decodeGeneratorEffectAtIndex(rawIndex + 3, 0)
    if (ancestral?.effectId === decoded.effectId && ancestral.rarity === 'ancestral') {
      return ancestral
    }
  }
  return decoded
}

/** Map equipped module \`effects\` array (0 = empty slot) to workshop picks. */
export function gameSubmoduleImportFromEffectIndices(
  slot: WorkshopAssistModuleSlot,
  effectIndices: readonly number[],
  moduleLevel = 0,
  primaryModuleLevel = 0,
  chassisMerge?: WorkshopChassisModuleMergeTier | null,
): {
  map: WorkshopSubmoduleSelectionMap
  ordered: WorkshopSubmoduleOrderedSlots
} {
  const ordered: WorkshopSubmoduleOrderedSlots = Array.from(
    { length: WORKSHOP_SUBMODULE_SLOT_COUNT },
    () => null,
  )
  const map: WorkshopSubmoduleSelectionMap = {}
  for (let si = 0; si < effectIndices.length && si < ordered.length; si++) {
    const raw = effectIndices[si]!
    if (raw === 0) continue
    const decoded = gameModuleEffectForSubmoduleImport(
      raw,
      slot,
      moduleLevel,
      primaryModuleLevel,
      chassisMerge,
    )
    if (decoded == null) continue
    const pick = { effectId: decoded.effectId, rarity: decoded.rarity }
    ordered[si] = pick
    map[decoded.effectId] = decoded.rarity
  }
  return { map, ordered }
}

/** Map equipped module \`effects\` array (0 = empty slot) to workshop selection map. */
export function gameSubmoduleSelectionFromEffectIndices(
  slot: WorkshopAssistModuleSlot,
  effectIndices: readonly number[],
  moduleLevel = 0,
  primaryModuleLevel = 0,
  chassisMerge?: WorkshopChassisModuleMergeTier | null,
): WorkshopSubmoduleSelectionMap {
  return gameSubmoduleImportFromEffectIndices(
    slot,
    effectIndices,
    moduleLevel,
    primaryModuleLevel,
    chassisMerge,
  ).map
}
`

writeFileSync(outPath, ts, 'utf8')
console.log('Wrote', outPath, `(${ENTRIES.length} effects)`)
touchWikiDataStamp('gen-game-module-effect-index')
