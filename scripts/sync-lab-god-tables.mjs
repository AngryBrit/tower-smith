/**
 * Regenerates imports + LAB_GOD_TABLES in src/data/labGodTables.ts from all tables/labs JSON.
 * Run: node scripts/sync-lab-god-tables.mjs
 */

import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')
const outFile = path.join(root, 'src/data/labGodTables.ts')

function camelCase(slug) {
  const parts = slug.split('-').filter(Boolean)
  return parts
    .map((p, i) => (i === 0 ? p : p.charAt(0).toUpperCase() + p.slice(1)))
    .join('')
}

function collectJsonFiles() {
  const files = []
  function walk(dir) {
    for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, ent.name)
      if (ent.isDirectory()) walk(p)
      else if (ent.name.endsWith('.json') && ent.name !== 'lab-order.json') {
        const rel = path.relative(path.join(root, 'tables/labs'), p).replace(/\\/g, '/')
        const doc = JSON.parse(fs.readFileSync(p, 'utf8'))
        if (doc.name) files.push({ rel, name: doc.name })
      }
    }
  }
  walk(path.join(root, 'tables/labs'))
  return files.sort((a, b) => a.name.localeCompare(b.name))
}

function importId(rel, used) {
  const base = camelCase(path.basename(rel, '.json'))
  const folder = camelCase(path.dirname(rel).split('/').pop() || 'lab')
  let id = base
  if (used.has(id)) id = folder + base.charAt(0).toUpperCase() + base.slice(1)
  if (used.has(id)) id = camelCase(rel.replace(/\//g, '-').replace('.json', ''))
  if (used.has(id)) throw new Error(`Duplicate import id for ${rel}`)
  used.add(id)
  return id
}

const files = collectJsonFiles()
const used = new Set()
const entries = files.map((f) => ({
  ...f,
  id: importId(f.rel, used),
}))

const imports = entries
  .map((e) => `import ${e.id} from '../../tables/labs/${e.rel}'`)
  .join('\n')

const tableBody = entries
  .map((e) => {
    const key = e.name.includes("'") ? `"${e.name}"` : `'${e.name}'`
    return `  ${key}: ${e.id} as LabGodTable,`
  })
  .join('\n')

const tail = `export type LabGodTime = {
  display: string
  seconds: number
}

export type LabGodLevel = {
  level: number
  value: number
  time: LabGodTime
  gems: number
  coins: number
  totalTime: LabGodTime
  totalGems: number
  totalCoins: number
}

export type LabGodTable = {
  name: string
  maxLevel: number
  levels: LabGodLevel[]
}

export const LAB_GOD_TABLES: Record<string, LabGodTable> = {
${tableBody}
}

/** Research card display names with a GOD table in \`tables/labs/\`. */
export const LAB_GOD_LAB_NAMES: ReadonlySet<string> = new Set(
  Object.keys(LAB_GOD_TABLES),
)

/** Target level row (upgrade ending at \`targetLevel\`) from a GOD table, if present. */
export function labGodLevelEntry(
  labDisplayName: string,
  targetLevel: number,
): LabGodLevel | undefined {
  const table = LAB_GOD_TABLES[labDisplayName]
  if (!table || !Number.isFinite(targetLevel) || targetLevel < 1) return undefined
  return table.levels.find((row) => row.level === targetLevel)
}
`

const header = `/**
 * Authoritative lab ladder data from \`tables/labs/\` JSON (lab calculator screenshots).
 * Marginal coins and upgrade times for these labs override \`tower-labs.json\`.
 * Generated by scripts/sync-lab-god-tables.mjs — do not hand-edit imports or LAB_GOD_TABLES.
 */

`

fs.writeFileSync(outFile, `${header}${imports}\n\n${tail}`)
console.log(`Wrote ${outFile} (${entries.length} labs)`)
