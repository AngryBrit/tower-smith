/**
 * Regenerates src/data/labGodTables.ts (types + runtime store) from tables/labs JSON.
 * Also refreshes public/tables/labs via copy script.
 *
 * Run: node scripts/sync-lab-god-tables.mjs
 */

import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { spawnSync } from 'node:child_process'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')
const outFile = path.join(root, 'src/data/labGodTables.ts')

function collectJsonFiles() {
  const files = []
  function walk(dir) {
    for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, ent.name)
      if (ent.isDirectory()) walk(p)
      else if (ent.name.endsWith('.json') && ent.name !== 'lab-order.json') {
        const rel = path.relative(path.join(root, 'tables/labs'), p).replace(/\\/g, '/')
        const doc = JSON.parse(fs.readFileSync(p, 'utf8'))
        if (doc.name) files.push({ rel, name: doc.name })
      }
    }
  }
  walk(path.join(root, 'tables/labs'))
  return files.sort((a, b) => a.name.localeCompare(b.name))
}

const files = collectJsonFiles()

const body = `/**
 * Authoritative lab ladder data from \`tables/labs/\` JSON.
 * Marginal coins and upgrade times for these labs override \`tower-labs.json\`.
 * Loaded at runtime from \`public/tables/labs/\` (see loadGodTables.ts).
 * Generated by scripts/sync-lab-god-tables.mjs — do not hand-edit store helpers.
 */

export type LabGodTime = {
  display: string
  seconds: number
}

export type LabGodLevel = {
  level: number
  value: number
  time: LabGodTime
  gems: number
  coins: number
  totalTime: LabGodTime
  totalGems: number
  totalCoins: number
}

export type LabGodTable = {
  name: string
  maxLevel: number
  levels: LabGodLevel[]
}

let labGodTables: Record<string, LabGodTable> = {}

/** Expected lab GOD table count (manifest sanity check). */
export const LAB_GOD_TABLE_COUNT = ${files.length}

export function installLabGodTables(tables: Record<string, LabGodTable>): void {
  labGodTables = tables
}

export function getLabGodTables(): Readonly<Record<string, LabGodTable>> {
  return labGodTables
}

export function getLabGodLabNames(): ReadonlySet<string> {
  return new Set(Object.keys(labGodTables))
}

/** Target level row (upgrade ending at \`targetLevel\`) from a GOD table, if present. */
export function labGodLevelEntry(
  labDisplayName: string,
  targetLevel: number,
): LabGodLevel | undefined {
  const table = labGodTables[labDisplayName]
  if (!table || !Number.isFinite(targetLevel) || targetLevel < 1) return undefined
  return table.levels.find((row) => row.level === targetLevel)
}
`

fs.writeFileSync(outFile, body)
console.log(`Wrote ${outFile} (${files.length} labs)`)

const copy = spawnSync(process.execPath, ['scripts/copy-god-tables-to-public.mjs'], {
  cwd: root,
  stdio: 'inherit',
})
if (copy.status !== 0) process.exit(copy.status ?? 1)
