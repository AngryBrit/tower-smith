/**
 * Generate EP-only Plus ability tracks from UWs Dropdown Export TSV (column G).
 * Usage: node scripts/gen-uw-ep-plus-tracks.mjs "path/to/export.tsv"
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const tsvPath = process.argv[2]
if (!tsvPath) {
  console.error('Usage: node scripts/gen-uw-ep-plus-tracks.mjs <tsv-path>')
  process.exit(1)
}

const PLUS_ROWS = {
  ultimatePlusChainLightningSmiteLevel: 5,
  ultimatePlusSmartMissilesCoverFireLevel: 9,
  ultimatePlusDeathWaveKillWallLevel: 13,
  ultimatePlusChronoFieldChronoLoopLevel: 17,
  ultimatePlusInnerLandMinesChargedMinesLevel: 21,
  ultimatePlusGoldenTowerGoldenComboLevel: 25,
  ultimatePlusPoisonSwampDeathCreepLevel: 29,
  ultimatePlusBlackHoleConsumeLevel: 33,
  ultimatePlusSpotlightLightRangeLevel: 37,
}

const OPTION_RE =
  /(\d{2}) \| ([^|]+?) \| Cost (\d+) ⧌ \| (?:Next (\d+) ⧌|Maxed)/g

const lines = readFileSync(tsvPath, 'utf8').split(/\r?\n/)
const lineByRow = new Map()
for (const line of lines) {
  const m = line.match(/^G(\d+)\s+(.+)$/)
  if (m) lineByRow.set(Number(m[1]), m[2])
}

const tracks = {}
for (const [key, row] of Object.entries(PLUS_ROWS)) {
  const raw = lineByRow.get(row)
  if (!raw) {
    console.error('Missing G' + row + ' for ' + key)
    process.exit(1)
  }
  const text = raw.replace(/^Lo\s*\|\s*Locked\s*/i, '')
  const milestones = []
  for (const match of text.matchAll(OPTION_RE)) {
    const level = Number.parseInt(match[1], 10)
    const marginalStones = level === 0 ? 0 : Number.parseInt(match[3], 10)
    milestones.push({ level, marginalStones, stat: match[2].trim() })
  }
  tracks[key] = milestones
  console.log(key, milestones.length, 'levels')
}

const outPath = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'effectivePaths', 'uwEpPlusTracks.generated.ts')
const body = `/** Generated by scripts/gen-uw-ep-plus-tracks.mjs — do not edit by hand. */

export type UwEpPlusMilestone = {
  readonly level: number
  readonly marginalStones: number
  readonly stat: string
}

export const UW_EP_PLUS_MILESTONES: Record<string, readonly UwEpPlusMilestone[]> = ${JSON.stringify(tracks, null, 2)} as const
`

writeFileSync(outPath, body)
console.log('Wrote', outPath)
