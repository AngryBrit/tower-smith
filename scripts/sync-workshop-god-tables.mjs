/**
 * Regenerates src/data/workshopGodTables.ts (types + runtime store) from
 * tables/workshop/ JSON. Also refreshes public/tables/workshop via copy script.
 *
 * Run: node scripts/sync-workshop-god-tables.mjs
 */

import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { spawnSync } from 'node:child_process'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')
const outFile = path.join(root, 'src/data/workshopGodTables.ts')

function collectJsonFiles() {
  const files = []
  const base = path.join(root, 'tables/workshop')
  function walk(dir) {
    for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, ent.name)
      if (ent.isDirectory()) walk(p)
      else if (ent.name.endsWith('.json')) {
        const rel = path.relative(base, p).replace(/\\/g, '/')
        const doc = JSON.parse(fs.readFileSync(p, 'utf8'))
        if (doc.name) files.push({ rel, name: doc.name })
      }
    }
  }
  if (fs.existsSync(base)) walk(base)
  return files.sort((a, b) => a.name.localeCompare(b.name))
}

const files = collectJsonFiles()

const body = `/**
 * Authoritative workshop ladder data from \`tables/workshop/\` JSON.
 * Loaded at runtime from \`public/tables/workshop/\` (see loadGodTables.ts).
 * Generated by scripts/sync-workshop-god-tables.mjs — do not hand-edit store helpers.
 */

export type WorkshopGodAmount = {
  display: string
  coins?: number | null
  cash?: number | null
  maxed?: boolean
}

export type WorkshopGodLevel = {
  level: number
  value: number | null
  valueDisplay?: string
  nextCoins: WorkshopGodAmount
  additionalCoins: WorkshopGodAmount
  totalCoins: WorkshopGodAmount
  /** Present on full workshop upgrade tables; omitted on enhancement tables. */
  nextCash?: WorkshopGodAmount
  additionalCash?: WorkshopGodAmount
  totalCash?: WorkshopGodAmount
  cashToTarget?: WorkshopGodAmount
  cashToMax?: WorkshopGodAmount
}

export type WorkshopGodTable = {
  name: string
  category: string
  maxLevel: number
  levels: WorkshopGodLevel[]
}

let workshopGodTables: Record<string, WorkshopGodTable> = {}

/** Expected workshop GOD table count (manifest sanity check). */
export const WORKSHOP_GOD_TABLE_COUNT = ${files.length}

export function installWorkshopGodTables(
  tables: Record<string, WorkshopGodTable>,
): void {
  workshopGodTables = tables
}

export function getWorkshopGodTables(): Readonly<Record<string, WorkshopGodTable>> {
  return workshopGodTables
}

export function getWorkshopGodUpgradeNames(): ReadonlySet<string> {
  return new Set(Object.keys(workshopGodTables))
}

/** Row for workshop level L from a GOD table, if present. */
export function workshopGodLevelEntry(
  upgradeDisplayName: string,
  level: number,
): WorkshopGodLevel | undefined {
  const table = workshopGodTables[upgradeDisplayName]
  if (!table || !Number.isFinite(level) || level < 0) return undefined
  return table.levels.find((row) => row.level === level)
}

/** Marginal coins for the upgrade ending at \`targetLevel\` (wiki **Next Coins** on row targetLevel−1). */
export function workshopGodMarginalCoins(
  upgradeDisplayName: string,
  targetLevel: number,
): number | undefined {
  if (!Number.isFinite(targetLevel) || targetLevel < 1) return undefined
  const row = workshopGodLevelEntry(upgradeDisplayName, targetLevel - 1)
  const coins = row?.nextCoins?.coins
  return typeof coins === 'number' && Number.isFinite(coins) ? coins : undefined
}
`

fs.writeFileSync(outFile, body)
console.log(`Wrote ${outFile} (${files.length} upgrades)`)

const copy = spawnSync(process.execPath, ['scripts/copy-god-tables-to-public.mjs'], {
  cwd: root,
  stdio: 'inherit',
})
if (copy.status !== 0) process.exit(copy.status ?? 1)
