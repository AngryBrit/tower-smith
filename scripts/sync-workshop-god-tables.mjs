/**
 * Regenerates imports + WORKSHOP_GOD_TABLES in src/data/workshopGodTables.ts
 * from all JSON under tables/workshop/.
 *
 * Run: node scripts/sync-workshop-god-tables.mjs
 */

import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')
const outFile = path.join(root, 'src/data/workshopGodTables.ts')

function camelCase(slug) {
  const parts = slug.split('-').filter(Boolean)
  return parts
    .map((p, i) => (i === 0 ? p : p.charAt(0).toUpperCase() + p.slice(1)))
    .join('')
}

function collectJsonFiles() {
  const files = []
  const base = path.join(root, 'tables/workshop')
  function walk(dir) {
    for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, ent.name)
      if (ent.isDirectory()) walk(p)
      else if (ent.name.endsWith('.json')) {
        const rel = path.relative(base, p).replace(/\\/g, '/')
        const doc = JSON.parse(fs.readFileSync(p, 'utf8'))
        if (doc.name) files.push({ rel, name: doc.name, category: doc.category ?? path.dirname(rel) })
      }
    }
  }
  if (fs.existsSync(base)) walk(base)
  return files.sort((a, b) => a.name.localeCompare(b.name))
}

function importId(rel, used) {
  const base = camelCase(path.basename(rel, '.json'))
  const folder = camelCase(path.dirname(rel).split('/').pop() || 'workshop')
  let id = base
  if (used.has(id)) id = folder + base.charAt(0).toUpperCase() + base.slice(1)
  if (used.has(id)) id = camelCase(rel.replace(/\//g, '-').replace('.json', ''))
  if (used.has(id)) throw new Error(`Duplicate import id for ${rel}`)
  used.add(id)
  return id
}

const files = collectJsonFiles()
const used = new Set()
const entries = files.map((f) => ({
  ...f,
  id: importId(f.rel, used),
}))

const imports = entries
  .map((e) => `import ${e.id} from '../../tables/workshop/${e.rel}'`)
  .join('\n')

const tableBody = entries
  .map((e) => {
    const key = e.name.includes("'") ? `"${e.name}"` : `'${e.name}'`
    return `  ${key}: ${e.id} as WorkshopGodTable,`
  })
  .join('\n')

const tail = `export type WorkshopGodAmount = {
  display: string
  coins?: number | null
  cash?: number | null
  maxed?: boolean
}

export type WorkshopGodLevel = {
  level: number
  value: number | null
  valueDisplay?: string
  nextCoins: WorkshopGodAmount
  additionalCoins: WorkshopGodAmount
  totalCoins: WorkshopGodAmount
  /** Present on full workshop upgrade tables; omitted on enhancement tables. */
  nextCash?: WorkshopGodAmount
  additionalCash?: WorkshopGodAmount
  totalCash?: WorkshopGodAmount
  cashToTarget?: WorkshopGodAmount
  cashToMax?: WorkshopGodAmount
}

export type WorkshopGodTable = {
  name: string
  category: string
  maxLevel: number
  levels: WorkshopGodLevel[]
}

export const WORKSHOP_GOD_TABLES: Record<string, WorkshopGodTable> = {
${tableBody}
}

/** Workshop upgrade display names with a GOD table in \`tables/workshop/\`. */
export const WORKSHOP_GOD_UPGRADE_NAMES: ReadonlySet<string> = new Set(
  Object.keys(WORKSHOP_GOD_TABLES),
)

/** Row for workshop level L from a GOD table, if present. */
export function workshopGodLevelEntry(
  upgradeDisplayName: string,
  level: number,
): WorkshopGodLevel | undefined {
  const table = WORKSHOP_GOD_TABLES[upgradeDisplayName]
  if (!table || !Number.isFinite(level) || level < 0) return undefined
  return table.levels.find((row) => row.level === level)
}

/** Marginal coins for the upgrade ending at \`targetLevel\` (wiki **Next Coins** on row targetLevel−1). */
export function workshopGodMarginalCoins(
  upgradeDisplayName: string,
  targetLevel: number,
): number | undefined {
  if (!Number.isFinite(targetLevel) || targetLevel < 1) return undefined
  const row = workshopGodLevelEntry(upgradeDisplayName, targetLevel - 1)
  const coins = row?.nextCoins?.coins
  return typeof coins === 'number' && Number.isFinite(coins) ? coins : undefined
}
`

const header = `/**
 * Authoritative workshop ladder data from \`tables/workshop/\` JSON (workshop calculator exports).
 * Generated by scripts/sync-workshop-god-tables.mjs — do not hand-edit imports or WORKSHOP_GOD_TABLES.
 */

`

fs.writeFileSync(outFile, `${header}${imports}\n\n${tail}`)
console.log(`Wrote ${outFile} (${entries.length} upgrades)`)
