/**
 * Generate game module infoIndex → workshop chassis id mapping.
 *
 * Game `modulesInfo` / `moduleIcons` use one global index per module design (not per slot).
 * Layout (49 entries, indices 0–48): per ModuleType in [cannon, armor, generator, core],
 * six generic placeholders (common×2 + rare×4) then six named epic chassis modules
 * in game sprite order (cannon_epic_1…4, then dedicated art).
 *
 * Calibrate with `npx tsx scripts/probe-module-inventory.mjs` and MANUAL_OVERRIDES below.
 *
 * Run: node scripts/gen-game-module-index.mjs
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { touchWikiDataStamp } from './lib/wiki-data-stamp.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outPath = join(root, 'src/playerSave/gameModuleIndex.ts')

/** @type {Record<number, string | null>} */
const MANUAL_OVERRIDES = {
  // Sample save (h:/The Tower/playerInfo.dat) — equipped + inventory calibration.
  6: null, // generic cannon placeholder — named Havoc Bringer is index 7
  7: 'havocBringer',
  8: 'deathPenalty',
  9: 'beingAnnihilator',
  10: 'astralDeliverance',
  18: 'negativeMassProjector',
  /** petethered.dat — armor assist Space Displacer (land-mine sub-stats). */
  19: 'spaceDisplacer',
  20: 'antiCubePortal',
  27: 'blackHoleDigestor',
  28: 'pulsarHarvester',
  29: 'galaxyCompressor',
  30: 'singularityHarness',
  37: 'multiverseNexus',
  38: 'dimensionCore',
  42: 'sharpFortitude',
  43: 'projectFunding',
  44: 'magneticHook',
  45: 'amplifyingStrike',
  46: 'orbitalAugment',
  47: 'restorativeBonus',
  48: 'primordialCollapse',
  /** James Wright.dat — equipped cannon legendary+ Shrink Ray (sub-stats decode; icon needs index). */
  41: 'shrinkRay',
}

/**
 * Unverified — inferred from calibrated index patterns (not yet seen in save).
 * Re-equip in-game to confirm; update MANUAL_OVERRIDES when verified.
 *
 * shrinkRay: continues cannon run 7–10; amplifyingStrike uses high index 45.
 * wormholeRedirector: armor index 21 (spaceDisplacer verified at 19 on petethered.dat).
 * harmonyConductor / omChip: core continues multiverse/dimension at 37–38 → 39–40.
 */
const GUESS_OVERRIDES = {
  11: 'shrinkRay',
  21: 'wormholeRedirector',
  39: 'harmonyConductor',
  40: 'omChip',
}

const SLOT_ORDER = ['cannon', 'armor', 'generator', 'core']

/** Named epic modules in game `moduleIcons` order (matches epic_1…4 + dedicated sprites). */
const NAMED_BY_SLOT = {
  cannon: [
    'havocBringer',
    'deathPenalty',
    'beingAnnihilator',
    'astralDeliverance',
    'shrinkRay',
    'amplifyingStrike',
  ],
  armor: [
    'wormholeRedirector',
    'antiCubePortal',
    'spaceDisplacer',
    'negativeMassProjector',
    'sharpFortitude',
    'orbitalAugment',
  ],
  generator: [
    'blackHoleDigestor',
    'pulsarHarvester',
    'galaxyCompressor',
    'singularityHarness',
    'projectFunding',
    'restorativeBonus',
  ],
  core: [
    'multiverseNexus',
    'dimensionCore',
    'harmonyConductor',
    'omChip',
    'primordialCollapse',
    'magneticHook',
  ],
}

/** @type {(string | null)[]} */
const GAME_MODULE_INFO_INDEX_TO_WORKSHOP_ID = []
for (const slot of SLOT_ORDER) {
  for (let i = 0; i < 6; i++) GAME_MODULE_INFO_INDEX_TO_WORKSHOP_ID.push(null)
  for (const id of NAMED_BY_SLOT[slot]) GAME_MODULE_INFO_INDEX_TO_WORKSHOP_ID.push(id)
}

if (GAME_MODULE_INFO_INDEX_TO_WORKSHOP_ID.length !== 48) {
  throw new Error(`expected 48 module indices, got ${GAME_MODULE_INFO_INDEX_TO_WORKSHOP_ID.length}`)
}
GAME_MODULE_INFO_INDEX_TO_WORKSHOP_ID.push(null)

for (const [idx, id] of Object.entries({ ...MANUAL_OVERRIDES, ...GUESS_OVERRIDES })) {
  const i = Number(idx)
  if (i < 0 || i >= GAME_MODULE_INFO_INDEX_TO_WORKSHOP_ID.length) continue
  GAME_MODULE_INFO_INDEX_TO_WORKSHOP_ID[i] = id
}

export const GAME_MODULE_INFO_COUNT = GAME_MODULE_INFO_INDEX_TO_WORKSHOP_ID.length

const lines = GAME_MODULE_INFO_INDEX_TO_WORKSHOP_ID.map((id, index) => {
  const comment = id == null ? 'generic / unknown' : id
  return `  ${id == null ? 'null' : JSON.stringify(id)}, // ${index}: ${comment}`
})

const ts = `/**
 * Game \`ModuleItem.infoIndex\` → workshop chassis module id.
 * Generated by \`scripts/gen-game-module-index.mjs\` — edit MANUAL_OVERRIDES there, then re-run.
 */

import type { WorkshopAssistModuleSlot } from '../data/workshopSimModules'
import { CHASSIS_MODULE_ORDERS } from '../data/workshopChassisModuleSelection'

export const GAME_MODULE_INFO_COUNT = ${GAME_MODULE_INFO_INDEX_TO_WORKSHOP_ID.length} as const

/** Save \`infoIndex\` → workshop id (\`null\` = generic module with no named chassis). */
export const GAME_MODULE_INFO_INDEX_TO_WORKSHOP_ID: readonly (string | null)[] = [
${lines.join('\n')}
] as const

export function gameWorkshopChassisModuleId(
  infoIndex: number,
  slot: WorkshopAssistModuleSlot,
): string | null {
  if (!Number.isFinite(infoIndex) || infoIndex < 0) return null
  const id = GAME_MODULE_INFO_INDEX_TO_WORKSHOP_ID[Math.trunc(infoIndex)] ?? null
  if (id == null) return null
  return CHASSIS_MODULE_ORDERS[slot].includes(id) ? id : null
}
`

writeFileSync(outPath, ts, 'utf8')
console.log('Wrote', outPath, `(${GAME_MODULE_INFO_INDEX_TO_WORKSHOP_ID.length} indices)`)
touchWikiDataStamp('gen-game-module-index')
